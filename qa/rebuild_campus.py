"""Inject the campus massing rebuilds (qa/rebuild/massing.js, then every qa/rebuild/b*.js in name order) into index.html as one
<script> block, after all earlier model passes and before the speed block. Re-runnable: the block between the markers is replaced.
usage (repo root): python qa/rebuild_campus.py"""
import glob, os
NL = '\r\n'; A = '<script>/* REBUILD-CAMPUS'; B = '</script><!-- /REBUILD-CAMPUS -->'
parts = ['qa/rebuild/massing.js'] + sorted(f.replace('\\', '/') for f in glob.glob('qa/rebuild/b*.js'))
js = NL.join(open(f, encoding='utf-8').read().rstrip() for f in parts).replace('\r\n', '\n').replace('\n', NL)
block = A + ' (generated by qa/rebuild_campus.py from ' + ', '.join(os.path.basename(f) for f in parts) + ') */' + NL + js + NL + B
s = open('index.html', encoding='utf-8', newline='').read()
if A in s:
    i = s.index(A); j = s.index(B, i) + len(B); s = s[:i] + block + s[j:]
else:
    anchor = '<script>/* speed 2026-10-29'; assert s.count(anchor) == 1; s = s.replace(anchor, block + NL + anchor)
open('index.html', 'w', encoding='utf-8', newline='').write(s); print('injected', [os.path.basename(f) for f in parts])
