"""Evidence level of every campus entry in index.html, from the audit inventory (qa/reports/buildings.csv, written by qa/audit.mjs
from the live page and the OSM extract qa/osm-campus.json). Writes the <script> block that index.html shows on cards and as a
colour overlay. Rules (no level is typed in by hand; the inputs are the flags and OSM comparisons in buildings.csv):

  footprint  VERIFIED   overlaps an OSM building with IoU >= 0.8, or has coordinate evidence recorded on the entry
             ESTIMATED  OSM IoU 0.5-0.8, drawn from the university plan (est), or not in OSM but listed in the audit as seen on imagery
             UNVERIFIED anything else (incl. 97: imagery shows trees where the outline is)
  height     VERIFIED   OSM building:levels equals the map's floor count
             ESTIMATED  floor count read from a photo, or OSM disagrees (78B), or drawn from the plan
             UNVERIFIED no source recorded
  roof       ESTIMATED  roof traced from imagery (72); UNVERIFIED for the rest (roof shapes were not compared with imagery entry by entry)
  facade     ESTIMATED  photo-fitted (photo reference on the entry); UNVERIFIED otherwise
  overall    VERIFIED = footprint and height verified; ESTIMATED = footprint verified or estimated; UNVERIFIED = footprint unverified
usage (repo root): python qa/campus_fidelity.py   -> rewrites the block between the FIDELITY-CAMPUS markers in index.html
"""
import csv, json, re
rows = list(csv.DictReader(open('qa/reports/buildings.csv', encoding='utf-8-sig')))
SEEN_ON_IMAGERY = {'52', '71', '98', 'seven'}   # qa/REPORT.md section B: not in OSM, imagery shows a building inside the outline
out = {}; n = {'V': 0, 'E': 0, 'U': 0}
for r in rows:
    f = r['sourceFlags']; iou = float(r['osmIoU']) if r['osmIoU'] else 0; flat = r['flat'] == 'true'
    if r['id'] == '97': fp = 'U'
    elif iou >= 0.8 or 'coordinateEvidence' in f: fp = 'V'
    elif iou >= 0.5 or 'est(' in f or r['id'] in SEEN_ON_IMAGERY: fp = 'E'
    else: fp = 'U'
    if flat: h = '-'
    elif r['osmLevels'] and r['osmLevels'] == r['lv']: h = 'V'
    elif r['osmLevels'] or 'photo' in f or 'est(' in f or r['id'] == '73': h = 'E'
    else: h = 'U'
    roof = '-' if flat else ('E' if 'imageryRoof' in f else 'U')
    fac = '-' if flat else ('E' if 'photo' in f else 'U')
    lvl = 'V' if fp == 'V' and h == 'V' else 'E' if fp in 'VE' else 'U'
    src = []
    if iou: src.append(f"OSM way {r['osmWay']} (IoU {iou:.2f})")
    if r['osmLevels']: src.append(f"OSM building:levels={r['osmLevels']}")
    if 'coordinateEvidence' in f: src.append('พิกัดอ้างอิงที่บันทึกไว้ในข้อมูลอาคาร')
    if 'est(' in f: src.append('แผนผังมหาวิทยาลัย (ประมาณ)')
    if 'photo' in f: src.append('รูปถ่ายอาคาร')
    if 'imageryRoof' in f: src.append('ภาพดาวเทียม (หลังคา)')
    out[r['id']] = [lvl, fp, h, roof, fac, ' · '.join(src)]; n[lvl] += 1
print(n)
block = ('<script>/* FIDELITY-CAMPUS 2026-10-29 (generated by qa/campus_fidelity.py, rules in that file): evidence level per entry,\n'
         '   [overall, footprint, height, roof, facade, sources]; V verified, E estimated, U unverified, - not applicable. */\n'
         'window.CAMPUS_FID=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n' +
         open('qa/campus-fidelity-ui.js', encoding='utf-8').read() + '\n</script><!-- /FIDELITY-CAMPUS -->')
s = open('index.html', encoding='utf-8', newline='').read(); nl = '\r\n' if '\r\n' in s else '\n'; block = block.replace('\n', nl)
if '/* FIDELITY-CAMPUS' in s:
    a = s.index('<script>/* FIDELITY-CAMPUS'); b = s.index('<!-- /FIDELITY-CAMPUS -->') + len('<!-- /FIDELITY-CAMPUS -->')
    s = s[:a] + block + s[b:]
else:
    anchor = "li.textContent='หมายเหตุการตรวจ (29 ต.ค. 2569) · '+t;ul.appendChild(li);}return r;};})();" + nl + '</script>'
    assert s.count(anchor) == 1; s = s.replace(anchor, anchor + nl + block)
    btn = '<button class="btn" id="night" type="button">กลางคืน</button>'
    assert s.count(btn) == 1; s = s.replace(btn, btn + nl + '    <button class="btn" id="fidBtn" type="button" aria-pressed="false">ความน่าเชื่อถือข้อมูลอาคาร</button>')
open('index.html', 'w', encoding='utf-8', newline='').write(s)
